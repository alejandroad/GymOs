// Runs drizzle-kit generate (forwarding any arguments, e.g. --name), then
// bundles the SQL migrations into a TypeScript module so the store worker
// imports them like code: no runtime fetch and no bundler loader config.
// Usage: pnpm db:generate --name <what_changed>
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

// Run drizzle-kit's bin with this Node directly: no shell and no .cmd shim,
// so it behaves the same on Windows, macOS and Linux. Its exports map hides
// bin.cjs, so locate it next to the package entry.
const kitBin = join(dirname(createRequire(import.meta.url).resolve("drizzle-kit")), "bin.cjs");
const kit = spawnSync(process.execPath, [kitBin, "generate", ...process.argv.slice(2)], {
  stdio: "inherit",
});
if (kit.status !== 0) process.exit(kit.status ?? 1);

const root = new URL("../", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("drizzle/meta/_journal.json", root), "utf8"));

const migrations = journal.entries
  .toSorted((a, b) => a.idx - b.idx)
  .map(({ tag }) => ({
    tag,
    sql: readFileSync(new URL(`drizzle/${tag}.sql`, root), "utf8").replaceAll("\r\n", "\n"),
  }));

const source = `// Generated by scripts/generate-migrations.mjs from drizzle/. Do not edit.
import type { Migration } from "./migrate";

export const migrations: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};
`;

writeFileSync(new URL("src/migrations.generated.ts", root), source);
console.log(`Bundled ${migrations.length} migration(s) into src/migrations.generated.ts`);
